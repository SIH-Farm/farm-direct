// ----- Helper: Get farmer by ID -----
export function getFarmerById(id) {
  return farmers.find(f => f.id === id);
}

// ----- Helper: Get products by farmer -----
export function getProductsByFarmer(farmerId) {
  return products.filter(p => p.farmerId === farmerId);
}

// ----- Helper: Get orders by farmer -----
export function getOrdersByFarmer(farmerId) {
  return orders.filter(o => o.farmerId === farmerId);
}

// ----- Helper: Calculate savings -----
export function calculateSavings(platformPrice, retailPrice) {
  const saving = retailPrice - platformPrice;
  const percent = Math.round((saving / retailPrice) * 100);
  return { saving, percent };
}

// ----- Helper: Format currency -----
export function formatCurrency(amount) {
  if (amount >= 10000000) {
    return `₹${(amount / 10000000).toFixed(1)} Cr`;
  }
  if (amount >= 100000) {
    return `₹${(amount / 100000).toFixed(1)} L`;
  }
  return `₹${amount.toLocaleString('en-IN')}`;
}

// ----- Helper: Get status color -----
export function getStatusBadge(status) {
  const map = {
    delivered: { label: 'Delivered', class: 'badge-green' },
    in_transit: { label: 'In Transit', class: 'badge-blue' },
    confirmed: { label: 'Confirmed', class: 'badge-amber' },
    processing: { label: 'Processing', class: 'badge-amber' },
    cancelled: { label: 'Cancelled', class: 'badge-red' },
    pending: { label: 'Pending', class: 'badge-gray' },
    paid: { label: 'Paid', class: 'badge-green' },
  };
  return map[status] || { label: status, class: 'badge-gray' };
}
